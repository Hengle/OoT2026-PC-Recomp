def apply(root):
    root = Path(root)
    for name in ('ocr_rupee_rgba.h', 'ocr_rupee_roll.h'):
        shutil.copy2(HERE / 'hud' / name, root / 'gpu/vk' / name)
    for rel, old, new in CHANGES:
        path = root / rel
        text = replace_once(path.read_text(encoding='utf-8'), old, new)
        path.write_text(text, encoding='utf-8', newline='\n')



