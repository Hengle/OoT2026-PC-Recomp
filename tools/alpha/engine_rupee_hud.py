def atlas_data():
    from PIL import Image
    frames, durations = [], []
    with Image.open(SOURCE) as gif:
        for i in range(gif.n_frames):
            gif.seek(i)
            frames.append(gif.convert('RGBA'))
            durations.append(max(10, int(gif.info.get('duration', 100))))
    boxes = [f.getchannel('A').getbbox() for f in frames]
    box = (min(b[0] for b in boxes), min(b[1] for b in boxes),
           max(b[2] for b in boxes), max(b[3] for b in boxes))
    height = 112
    width = round(height * (box[2] - box[0]) / (box[3] - box[1]))
    # Transparent two-pixel gutters prevent filtering between atlas cells.
    cell_w, cell_h, cols = width + 4, height + 4, 3
    atlas = Image.new('RGBA', (cols * cell_w, math.ceil(len(frames) / cols) * cell_h))
    for i, frame in enumerate(frames):
        frame = frame.crop(box).resize((width, height), Image.Resampling.LANCZOS)
        atlas.paste(frame, ((i % cols) * cell_w + 2, (i // cols) * cell_h + 2))
    return atlas, durations, width, height, cell_w, cell_h, cols


def header_text():
    atlas, durations, width, height, cell_w, cell_h, cols = atlas_data()
    data = atlas.tobytes()
    lines = ['// Generated by tools/alpha/engine_rupee_hud.py from hud/rainbow-rupee.gif.',
             '#pragma once',
             f'static const int ocr_rupee_w = {atlas.width}, ocr_rupee_h = {atlas.height};',
             f'static const int ocr_rupee_fw = {width}, ocr_rupee_fh = {height};',
             f'static const int ocr_rupee_cw = {cell_w}, ocr_rupee_ch = {cell_h}, ocr_rupee_cols = {cols};',
             f'static const int ocr_rupee_frames = {len(durations)}, ocr_rupee_period = {sum(durations)};',
             'static const int ocr_rupee_ms[] = {' + ','.join(map(str, durations)) + '};',
             f'static const unsigned char ocr_rupee_rgba[{len(data)}] = {{']
    lines += [','.join(map(str, data[i:i+32])) + ',' for i in range(0, len(data), 32)]
    return '\n'.join(lines + ['};', ''])


