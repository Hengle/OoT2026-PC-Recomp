"""The F1 menu banner's mark: the project's own ocarina picture instead of a hand-drawn outline.

The outline was a concave path filled as if it were convex, which Dear ImGui draws with stray triangles. The banner now
shows the same picture as the launcher (tools/alpha/launcher/assets/ocarina-112.png), as one small texture beside the start-up logo.
hud/ocr_mark_rgba.h holds its pixels; `python engine_mark.py` writes it again (needs Pillow, as make_project_art.py does).
UI-only: no shader, translator or cache input changes.
"""
from pathlib import Path
import shutil
from engine_stability import replace_once
from engine_theme import replace_function

HERE = Path(__file__).parent
HEADER = HERE / 'hud/ocr_mark_rgba.h'
SOURCE = HERE / 'launcher/assets/ocarina-112.png'   # (the launcher's own picture, its largest size)
SIZE = 80   # (the banner draws it 40 units high: 1:1 at 2160p, half size at 1080p)


def header_text():
    from PIL import Image
    picture = Image.open(SOURCE).convert('RGBA')
    picture = picture.crop(picture.getchannel('A').getbbox())
    side = max(picture.size)
    square = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    square.paste(picture, ((side - picture.width) // 2, (side - picture.height) // 2))
    px = square.resize((SIZE, SIZE), Image.Resampling.LANCZOS).tobytes()
    lines = ['// generated by tools/alpha/engine_mark.py from tools/alpha/launcher/assets/ocarina-112.png: do not edit',
             '#pragma once',
             'static const unsigned ocr_mark_w = %d, ocr_mark_h = %d;' % (SIZE, SIZE),
             'static const unsigned char ocr_mark_rgba[%d] = {' % len(px)]
    lines += [','.join(str(b) for b in px[i:i + 32]) + ',' for i in range(0, len(px), 32)]
    return '\n'.join(lines + ['};']) + '\n'


def apply(root):
    vk = Path(root) / 'gpu/vk'
    shutil.copy2(HEADER, vk / 'ocr_mark_rgba.h')

    def edit(name, change):
        path = vk / name
        path.write_text(change(path.read_text(encoding='utf-8')), encoding='utf-8', newline='\n')

    def imgui(t):
        t = replace_once(t, 'namespace mkwvk::ui {',
            '#include "ocr_mark_rgba.h"   // (Ocarina Reborn: the banner mark)\n\nnamespace mkwvk::ui {')
        t = replace_once(t, 'float logo_aspect = 1;', 'float logo_aspect = 1;\nImTextureData* mark_ = nullptr;')
        t = replace_once(t, '    logf("vk: ui: Dear ImGui %s on the window\'s images',
            '    mark_ = IM_NEW(ImTextureData)();\n'
            '    mark_->Create(ImTextureFormat_RGBA32, (int)ocr_mark_w, (int)ocr_mark_h);\n'
            '    memcpy(mark_->GetPixels(), ocr_mark_rgba, (size_t)ocr_mark_w * ocr_mark_h * 4);\n'
            '    mark_->UseColors = true;\n'
            '    ImGui::RegisterUserTexture(mark_);\n'
            '    logf("vk: ui: Dear ImGui %s on the window\'s images')
        return replace_once(t, 'void idle() {', 'ImTextureData* mark() { return mark_; }\n\nvoid idle() {')
    edit('vk_imgui.cpp', imgui)
    edit('vk_imgui.h', lambda t: replace_once(t, 'ImTextureData* logo(float* aspect);',
        'ImTextureData* logo(float* aspect);\n'
        '/// (Ocarina Reborn) the banner\'s mark, the launcher\'s ocarina picture (square), or null before the first frame\n'
        'ImTextureData* mark();'))
    edit('vk_ui.h', lambda t: replace_function(t, 'inline void ocarina(',
        '''inline void ocarina(Ctx& c, ImVec2 p, float size) {
    // (the launcher's own picture; p is its top left, size its side)
    if (ImTextureData* picture = mark()) c.d->AddImage(picture->GetTexRef(), p, p + ImVec2(size, size));
}'''))

    def menu(t):
        t = replace_once(t, '            ui::ocarina(c,ImVec2(x0,ty-18*s),36*s);\n'
            '            c.d->AddLine(ImVec2(x0+tri+4*s,ty-14*s),ImVec2(x0+tri+4*s,ty+14*s),ui::kBannerEdge,std::max(1.f,s));\n'
            '            const float tx = x0 + tri + 12 * s, text_room = room - tri - 12 * s;',
            '            ui::ocarina(c,ImVec2(x0,ty-20*s),40*s);\n'
            '            c.d->AddLine(ImVec2(x0+tri+10*s,ty-14*s),ImVec2(x0+tri+10*s,ty+14*s),ui::kBannerEdge,std::max(1.f,s));\n'
            '            const float tx = x0 + tri + 20 * s, text_room = room - tri - 20 * s;')
        return replace_once(t, 'x0 = c.safe, tri = 30 * s;', 'x0 = c.safe, tri = 40 * s;')
    edit('vk_menu.cpp', menu)


if __name__ == '__main__':
    HEADER.write_text(header_text(), encoding='utf-8', newline='\n')
    print('engine_mark:', HEADER)
